function toCallouts(list: Row[]): Callout[] {
  return list.map(([en, ru, uk, de]) => ({
    id: en.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
    names: { en, ru, uk, de },
  }));
}

export function calloutsFor(mapId: string): Callout[] {
  return toCallouts(rows[mapId] ?? []);
}
